/** Get a single checklist step by number (1-based) */
export function getStep(stepNumber: number): ChecklistStep | undefined {
  return checklistSteps.find((s) => s.number === stepNumber);
}

/** Calculate overall progress based on completed and skipped steps */
export function calculateProgress(
  completed: number[],
  skipped: number[]
): { current: number; total: number; percentage: number } {
  const total = checklistSteps.length;
  const current = completed.length + skipped.length;
  const percentage = total > 0 ? Math.round((current / total) * 100) : 0;
  return { current, total, percentage };
}
